#include <unistd.h>
#include <signal.h>
#include <stdio.h>
#include <stdlib.h>
#include <sys/wait.h>


int pid1, pid2;  // 子进程1、2的PID
int fd[2];       // 管道文件描述符：fd[0]读端，fd[1]写端
char InPipe[4001];  // 读缓冲区（存4000个字符+1个结束符）

int main() {
    // 步骤1：创建匿名管道（仅能用于父子进程通信）
    if (pipe(fd) == -1) {  // 管道创建失败
        perror("pipe create error");
        exit(1);
    }

    // 步骤2：创建子进程1（写2000个字符'1'）
    while ((pid1 = fork()) == -1);
    if (pid1 == 0) {
        close(fd[0]);  // 子进程1只写不读，关闭读端（必须关，否则父进程读会阻塞）
        
        // ------------------- 有锁/无锁切换 -------------------
        lockf(fd[1], 1, 0);  // 1. 有锁：锁定管道写端（防止子进程2同时写）
        // （无锁时，注释掉上面这行lockf）
        // ------------------------------------------------------
        
        // 写2000个'1'到管道
        for (int i = 0; i < 2000; i++) {
            write(fd[1], "1", 1);  // 每次写1个字符
        }
        
        // ------------------- 有锁/无锁切换 -------------------
        lockf(fd[1], 0, 0);  // 1. 有锁：解锁管道写端
        // （无锁时，注释掉上面这行lockf）
        // ------------------------------------------------------
        
        close(fd[1]);  // 写完关闭写端
        exit(0);
    }

    // 步骤3：创建子进程2（写2000个字符'2'）
    while ((pid2 = fork()) == -1);
    if (pid2 == 0) {
        close(fd[0]);  // 子进程2只写不读，关闭读端
        
        // ------------------- 有锁/无锁切换 -------------------
        lockf(fd[1], 1, 0);  // 1. 有锁：锁定管道写端
        // （无锁时，注释掉上面这行lockf）
        // ------------------------------------------------------
        
        // 写2000个'2'到管道
        for (int i = 0; i < 2000; i++) {
            write(fd[1], "2", 1);
        }
        
        // ------------------- 有锁/无锁切换 -------------------
        lockf(fd[1], 0, 0);  // 1. 有锁：解锁管道写端
        // （无锁时，注释掉上面这行lockf）
        // ------------------------------------------------------
        
        close(fd[1]);  // 写完关闭写端
        exit(0);
    }

    // 步骤4：父进程的逻辑（读管道数据并显示）
    close(fd[1]);  // 父进程只读不写，关闭写端（必须关，否则读会阻塞）
    
    // 等待两个子进程写完（避免父进程先读导致读不到数据）
    wait(NULL);
    wait(NULL);
    
    // 从管道读4000个字符到缓冲区
    read(fd[0], InPipe, 4000);
    InPipe[4000] = '\0';  // 加字符串结束符（否则printf可能乱码）
    
    // 输出结果
    printf("管道中读出的数据（共4000个字符）：\n");
    printf("%s\n", InPipe);
    
    close(fd[0]);  // 读完关闭读端
    exit(0);
}
